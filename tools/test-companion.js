/* Isolated regression checks: no browser storage, accounts, or personal data. */
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const context = { window: {}, console, Date, setTimeout: () => 0, clearTimeout() {}, localStorage: { removeItem() {} } };
context.window.LO = { ui: { esc: s => String(s) } };
vm.createContext(context);
for (const file of ['store', 'level', 'aims', 'adaptive', 'companion', 'notifications', 'fareharbor']) vm.runInContext(fs.readFileSync('assets/js/' + file + '.js', 'utf8'), context);
const { store, D, aims, adaptive, level, notify, fareharbor } = context.window.LO;
assert.equal((context.window.LO.companion.lumen('profile').match(/class="lumen-wedge"/g) || []).length, 40);
assert.ok(!context.window.LO.companion.boot.toString().includes("insertAdjacentHTML('beforeend', trail())"), 'the light shell must not mount the animated trail');
assert.equal(notify.status().supported, false);
assert.equal(notify.cfg().morningTime, '08:00');
assert.equal(notify.cfg().updateTime, '17:30');
assert.equal(notify.cfg().minGapHours, 6);
const shellSource = fs.readFileSync('assets/js/shell.js', 'utf8');
assert.ok(shellSource.includes('Quiet notifications'), 'settings need explicit notification controls');
assert.ok(shellSource.includes('Focus Orb') && shellSource.includes('Today Strip') && shellSource.includes('Circle Pulse'), 'settings need all three widget previews');
const workerSource = fs.readFileSync('sw.js', 'utf8');
assert.ok(workerSource.includes("addEventListener('push'") && workerSource.includes("addEventListener('notificationclick'"), 'service worker needs Web Push receiving hooks');
const indexSource = fs.readFileSync('index.html', 'utf8');
assert.ok(!indexSource.includes('data-pane="advice"'), 'Advice must not return as a pane');
assert.ok(!indexSource.includes('surfaces/advice.js'), 'Advice must not return as a loaded surface');
assert.ok(!indexSource.includes('customize.js'), 'the fixed paper system must not load the old theme editor');
assert.equal((indexSource.match(/data-pane=/g) || []).length, 3, 'the live app has exactly three destinations');
const doSurface = fs.readFileSync('assets/js/surfaces/do.js', 'utf8');
assert.ok(doSurface.includes('class="day-paper'), 'Do must open on the paper task list');
assert.ok(doSurface.indexOf('class="day-paper') < doSurface.indexOf('class="quote'), 'the task list must precede the quote');
assert.ok(!doSurface.includes('data-start'), 'the primary Start button must not return');
assert.ok(!doSurface.includes('data-board'), 'the dealt-action board must not gate the list');
assert.ok(doSurface.includes('holdableTasks(root)'), 'today rows need deliberate hold management');
assert.ok(doSurface.includes('LO.machine.taskMenu'), 'holding a task needs the shared management sheet');
assert.ok(!doSurface.includes('LO.companion.discovery()'), 'Explore content must stay off the focused Do page');
const meSurface = fs.readFileSync('assets/js/surfaces/me.js', 'utf8');
assert.ok(meSurface.includes('class="attention-inbox"'), 'Me needs the attention inbox');
assert.ok(meSurface.includes('class="profile-trajectory"'), 'trajectory belongs directly under the profile crest');
assert.ok(!meSurface.includes('guidancePanel()') && !meSurface.includes('class="mission"'), 'Guidance and mission copy must stay off Me');
const writeSurfaceSource = fs.readFileSync('assets/js/surfaces/write.js', 'utf8');
assert.ok(writeSurfaceSource.includes('class="write-pad"'), 'Write must be one continuous paper surface');
const paperSource = fs.readFileSync('assets/css/paper.css', 'utf8');
assert.ok(paperSource.includes('grid-template-columns:repeat(3,1fr)'), 'the bottom bar must centre three destinations');
assert.ok(paperSource.includes('.tab[data-go="write"] .tab-icon'), 'Write needs the larger circular centre action');
const buy = { title: 'Buy a used item', domain: 'craft', track: { kind: 'wins', winKind: 'ride', per: 1, what: 'rides' } };
const sell = { title: 'Sell an old item', domain: 'craft', track: { kind: 'wins', winKind: 'ride', per: 1, what: 'rides' } };
assert.equal(aims.resolve(buy).winKind, 'market-check');
assert.equal(aims.resolve(sell).winKind, 'sale-prep');
assert.match(aims.progress(buy, store.state).label, /0 of 3 marketplace checks this week/);
store.wipe();
store.capture('A daily task', 2);
assert.equal(store.dayList().length, 1);
assert.equal(store.state.scribe.entries.length, 0, 'Do must not write into the journal');
store.write('task', 'A written thought that sounds like a task');
assert.equal(store.dayList().length, 1, 'Write must not add to the daily list');
assert.equal(store.state.mind.load.length, 1, 'only the Do capture creates a task');
assert.equal(store.state.scribe.entries.length, 1);
const daily = store.dayList()[0];
const beforeDoneHistory = store.state.chronicle.length;
const paid = store.completeTask(daily.id);
assert.equal(paid.points, 25);
assert.equal(store.dayList()[0].status, 'closed');
assert.equal(store.state.wins.filter(w => w.ref === 'task_' + daily.id).length, 1);
store.reopenTask(daily.id);
assert.equal(store.dayList()[0].status, 'open');
assert.equal(store.state.wins.filter(w => w.ref === 'task_' + daily.id).length, 0, 'unchecking returns the task points');
assert.ok(store.state.chronicle.length > beforeDoneHistory, 'completion corrections append to history');
store.removeTask(daily.id);
assert.equal(store.dayList().length, 0);
const reminder = store.addReminder('A neutral reminder', D.shift(1));
assert.equal(store.state.inbox.reminders.length, 1);
store.completeReminder(reminder.id);
assert.equal(store.state.inbox.reminders[0].done, true);
store.notice('An update', 'Something changed.', 'test', 'one', '#inbox');
store.notice('An update', 'Latest copy.', 'test', 'one', '#inbox');
assert.equal(store.state.inbox.notices.length, 1, 'matching notices update instead of multiplying');
const normalizedTour = fareharbor.normalize({ id: 7, title: 'Example tour', start: '2026-09-17T09:00:00-04:00', assignedTo: ['Example Guide'] });
assert.equal(normalizedTour.id, '7');
assert.equal(fareharbor.matches(normalizedTour, 'example guide'), true);
assert.equal(fareharbor.matches(normalizedTour, 'someone else'), false);
fareharbor.configure({ bridgeUrl: 'https://bridge.example/tours', token: 'device-secret', guide: 'Example Guide' });
assert.equal(JSON.parse(store.export()).integrations.fareharbor.token, '', 'FareHarbor access key must never enter a backup');
store.write('thought', 'A detail worth retelling', {
  tags: ['field-story', 'nature'], prompt: 'What changed?',
  source: { id: 'example-source', title: 'A useful detail', name: 'Source', url: 'https://example.com' }
});
const storyEvent = store.state.chronicle.find(e => e.text === 'A detail worth retelling');
assert.ok(storyEvent.meta.tags.includes('field-story'), 'field stories need durable chronicle metadata');
assert.equal(storyEvent.meta.source.title, 'A useful detail');
const storyId = storyEvent.meta.ref;
assert.equal(store.shareStory(storyId), 10);
assert.equal(store.shareStory(storyId), 0, 'one story can pay at most once per day');
assert.equal(store.winsOn().filter(w => w.ref === 'field_share_' + storyId).length, 1);
const writeSurface = fs.readFileSync('assets/js/surfaces/write.js', 'utf8');
assert.ok(writeSurface.includes("label: 'Field stories'"), 'Write needs a separate story collection');
assert.ok(fs.readFileSync('assets/js/companion.js', 'utf8').includes('data-story="${f.id}"'), 'discoveries need a route into the field journal');
store.wipe();
assert.equal(adaptive.analyze(store.state).mode, 'explore');
store.log('thought', '<script>test</script>');
const entry = store.state.chronicle[0], original = JSON.stringify(entry);
store.hideEntry(entry.id);
assert.equal(store.visibleChronicle().length, 0);
assert.equal(JSON.stringify(store.state.chronicle[0]), original, 'history must be preserved');
store.hideEntry(entry.id, true);
assert.equal(store.visibleChronicle()[0].id, entry.id);
store.reclassifyEntry(entry.id, 'plan');
assert.equal(store.visibleChronicle()[0].type, 'plan');
assert.equal(JSON.stringify(store.state.chronicle[0]), original, 'refiling must not mutate the original event');
store.state.mind.logs = [0, 1, 2].map(n => ({ date: D.shift(-n), energy: 3 }));
assert.equal(adaptive.analyze(store.state).mode, 'gentle');
assert.ok(adaptive.weight({ minutes: 2 }, store.state) > adaptive.weight({ minutes: 10 }, store.state));
adaptive.feedback('reflection', false);
assert.ok(adaptive.preference('reflection', store.state) < 1);
adaptive.feedback('reflection', true);
assert.equal(store.state.guidance.feedback.length, 1, 'one current vote per method per day');
assert.ok(adaptive.preference('reflection', store.state) > 1);
store.state.guidance.enabled = false;
assert.equal(adaptive.weight({ minutes: 2 }, store.state), 1);
assert.equal(adaptive.preference('reflection', store.state), 1);
store.state.guidance.enabled = true;
store.state.mind.logs = [];
store.state.meta.created = D.shift(-20);
store.state.wins = Array.from({ length: 14 }, (_, i) => ({ date: D.shift(-i), kind: 'task', points: 10 }));
assert.equal(adaptive.analyze(store.state).mode, 'steady');
store.state.wins.push(...Array.from({ length: 4 }, () => ({ date: D.today(), kind: 'task', points: 25 })));
assert.equal(adaptive.analyze(store.state).mode, 'stretch');
const total = level.total();
store.import(store.export());
assert.equal(level.total(), total, 'backup round-trip preserves XP');
assert.equal(store.state.guidance.feedback.length, 1);
store.add('people', { name: 'Example', cadence: 14, lastContact: '', nextReach: D.shift(2) });
assert.equal(store.mostOverdue(), null, 'future contact plans should not be nagged');
const p = store.state.people[0];
store.contacted(p.id);
assert.equal(p.nextReach, D.shift(14));
assert.equal(p.lastContact, D.today());
console.log('PASS: three-tab paper shell, task management, attention inbox, FareHarbor boundary, paper Write, semantic aims, append-only corrections, recovery, adaptation, backup, contacts');
